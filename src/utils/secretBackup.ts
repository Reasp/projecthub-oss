/**
 * Удаление записи теряет значение безвозвратно: запись расшифровывается и отличается от текущего
 * значения ключа (`restorable`) или пока не читается этим профилем (`unreadable`) — ключ ОС может
 * вернуться. Запись, совпадающая с текущим значением (`current`), и запись без значения (`noValue`)
 * ничего не хранят сверх хранилища.
 */
export function isSoleCopy(item: { status: string }): boolean {
  return item.status === 'restorable' || item.status === 'unreadable';
}
